def entries(words=None):
    """`WORDS`를 `(낱말, 뜻번호 또는 None)` 목록으로 편다. 중복은 «먼저 온 것»을 쓴다."""
    seen, out = set(), []
    for item in (words if words is not None else WORDS):
        word, sense = item if isinstance(item, tuple) else (item, None)
        if word in seen:
            continue
        seen.add(word)
        out.append((word, sense))
    return out


def dedup(words):
    """순서를 지키며 중복을 없앤다. (낱말 문자열만 돌려준다)"""
    return [w for w, _ in entries(words)]
