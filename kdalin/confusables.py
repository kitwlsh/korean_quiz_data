def usable_pairs(text):
    """지문에서 쓸 수 있는 혼동쌍을 찾는다.

    🔴 **그 말이 지문에 «정확히 한 번»만 나올 때**로 제한한다.
    두 번 나오면 어느 쪽을 바꿨는지 `span`이 가리키지 못하고, 채점이 어긋난다.
    """
    out = []
    for right, wrong, head, sense, rule in PAIRS:
        if text.count(right) != 1:
            continue
        # 🔴 틀린 표기가 이미 지문에 있으면 건드리지 않는다 — 원문이 틀린 것이지 문제가 아니다.
        if wrong in text:
            continue
        out.append({
            'right': right,
            'wrong': wrong,
            'head': head,
            'sense': sense,
            'rule': rule,
            'at': text.index(right),
        })
    out.sort(key=lambda p: p['at'])
    return out
